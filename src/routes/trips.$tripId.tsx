import { useEffect, useState } from "react";
import { createFileRoute, Link } from "@tanstack/react-router";
import { ArrowLeft } from "lucide-react";

import { Button } from "@/components/ui/button";
import { SiteFooter, SiteHeader } from "@/components/trip/SiteHeader";
import { TripResults } from "@/components/trip/TripResults";
import { tripHistory } from "@/lib/trip/history";
import type { TripPlan } from "@/lib/trip/types";

export const Route = createFileRoute("/trips/$tripId")({
  head: () => ({
    meta: [
      { title: "Saved trip plan — TripSync AI" },
      {
        name: "description",
        content: "A saved day-wise itinerary, budget and route from TripSync AI.",
      },
      { property: "og:title", content: "Saved trip plan — TripSync AI" },
      {
        property: "og:description",
        content: "Itinerary, budget dashboard and route generated by TripSync AI agents.",
      },
      { property: "og:type", content: "article" },
      { name: "twitter:card", content: "summary" },
    ],
  }),
  component: TripPage,
});

function TripPage() {
  const { tripId } = Route.useParams();
  const [plan, setPlan] = useState<TripPlan | null | undefined>(undefined);
  useEffect(() => setPlan(tripHistory.get(tripId) ?? null), [tripId]);

  return (
    <div className="min-h-screen">
      <SiteHeader />
      <main className="mx-auto max-w-7xl px-4 py-10 sm:px-6">
        <Button variant="ghost" size="sm" asChild className="mb-6">
          <Link to="/history">
            <ArrowLeft /> All trips
          </Link>
        </Button>
        {plan === undefined ? null : plan === null ? (
          <div className="journal-card p-10 text-center">
            <p className="font-display text-2xl">Trip not found</p>
            <p className="mt-2 text-sm text-muted-foreground">
              It may have been deleted or saved on another device.
            </p>
          </div>
        ) : (
          <TripResults plan={plan} />
        )}
      </main>
      <SiteFooter />
    </div>
  );
}
